const ui: Record<Locale, Record<UiKey, string>> = { en, es };

/** Shared UI string; `{name}` placeholders are filled from `vars`. */
export function t(locale: Locale, key: UiKey, vars?: Record<string, string | number>): string {
  const text = ui[locale][key] ?? ui.en[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}
